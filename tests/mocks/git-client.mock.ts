export function makeCommitSelection(
  paths: readonly string[],
  overrides: Partial<CommitSelection> = {},
): CommitSelection {
  return {
    paths,
    head: "a".repeat(40),
    branchRef: "refs/heads/feat/test",
    tree: "b".repeat(40),
    diff: "diff --git a/src/app.ts",
    stat: { insertions: 0, deletions: 0 },
    ...overrides,
  };
}

